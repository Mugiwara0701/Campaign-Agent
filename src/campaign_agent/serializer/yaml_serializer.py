"""Overlay dict -> YAML text. Deterministic: the same data always gives the same bytes.

Built with yaml.dump (safe dumper) from typed values, never by string templating. The only text
outside the data is a comment header of fixed words, a hash and a sanitised id. It carries no
timestamp, so the sha256 of the file depends only on the content.
"""

import re
from collections.abc import Mapping
from typing import Any

import yaml
from pydantic import BaseModel

from campaign_agent.contract.model import CampaignOverlay

_ID_SAFE = re.compile(r"[^A-Za-z0-9_-]")


class _Dumper(yaml.SafeDumper):
    def ignore_aliases(self, data: Any) -> bool:
        return True  # never emit anchors or aliases, even for a shared list object

    def increase_indent(self, flow: bool = False, indentless: bool = False) -> None:
        super().increase_indent(flow, False)  # indent list items under their key


def _order(data: Mapping[str, Any], model: type[BaseModel]) -> dict[str, Any]:
    """Keys in the contract model's field order; unknown keys (invalid overlays) go last, sorted."""
    ordered: dict[str, Any] = {}
    for name, info in model.model_fields.items():
        if name not in data:
            continue
        value = data[name]
        sub = info.annotation
        if isinstance(value, Mapping) and isinstance(sub, type) and issubclass(sub, BaseModel):
            value = _order(value, sub)
        ordered[name] = value
    for name in sorted(set(data) - set(ordered)):
        ordered[name] = data[name]
    return ordered


def dump_body(data: Mapping[str, Any]) -> str:
    return yaml.dump(
        _order(data, CampaignOverlay),
        Dumper=_Dumper,
        sort_keys=False,
        default_flow_style=False,
        allow_unicode=True,
        width=100,
        indent=2,
    )


def header(*, ir_hash: str, campaign_id: str, contract_version: str, not_applied: int) -> str:
    safe_id = _ID_SAFE.sub("?", campaign_id)[:64]
    return (
        "# Campaign overlay generated by the Campaign Agent. Do not edit by hand.\n"
        f"# campaign: {safe_id}\n"
        f"# contract: {contract_version}\n"
        f"# ir: {ir_hash}\n"
        f"# not applied: {not_applied} request(s), listed in the version record\n"
    )


def serialize_overlay(
    data: Mapping[str, Any],
    *,
    ir_hash: str,
    campaign_id: str,
    contract_version: str,
    not_applied: int,
) -> str:
    head = header(
        ir_hash=ir_hash,
        campaign_id=campaign_id,
        contract_version=contract_version,
        not_applied=not_applied,
    )
    return head + dump_body(data)


def strip_header(text: str) -> str:
    lines = text.splitlines(keepends=True)
    i = 0
    while i < len(lines) and lines[i].startswith("#"):
        i += 1
    return "".join(lines[i:])
