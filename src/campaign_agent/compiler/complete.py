"""The complete leadgen.yaml for a campaign: the Marketing Agent's base file with the campaign applied, as one file.

The overlay says what the campaign changes; this is the whole file the Marketing Agent would run. It is built from the
RAW base text (not from the contract's model, which normalises values), so every value outside the campaign is exactly
what the base file holds, and the Marketing Agent can check that by plain equality. The file is validated with the full
contract before it is offered.

The base is a snapshot of the Marketing Agent's own file (contract/model.py: BASE_CONFIG_SOURCE). `base_fingerprint`
names that snapshot, so a Marketing Agent whose file has moved on notices and does not run stale lists.
"""

import copy
import hashlib
import json
from dataclasses import dataclass
from functools import lru_cache
from importlib import resources
from typing import Any

import yaml

from campaign_agent.contract.loader import load_full, parse_yaml
from campaign_agent.contract.model import CONFIG_VERSION

EXCLUDE_KEYS = ("exclude_terms", "exclude_companies", "exclude_countries", "exclude_tlds")
SECTIONS = ("project_context", "search", "qualification", "limits")


@dataclass(frozen=True)
class CompleteFile:
    text: str
    sha256: str
    base_sha256: str


@lru_cache(maxsize=1)
def _base_text() -> str:
    return (
        resources.files("campaign_agent.contract")
        .joinpath("base_config.yaml")
        .read_text(encoding="utf-8")
    )


def base_raw() -> dict[str, Any]:
    return yaml.safe_load(_base_text())  # type: ignore[no-any-return]


def fingerprint(raw: dict[str, Any]) -> str:
    """The same value the Marketing Agent computes from its own file: a hash of the parsed data, so comments and spacing
    do not matter."""
    canonical = json.dumps(raw, sort_keys=True, separators=(",", ":"), ensure_ascii=False)
    return hashlib.sha256(canonical.encode("utf-8")).hexdigest()


def base_fingerprint() -> str:
    return fingerprint(base_raw())


def _norm(text: str) -> str:
    return " ".join(str(text).casefold().split())


def merge_raw(overlay: dict[str, Any], base: dict[str, Any]) -> dict[str, Any]:
    """The rule of `merge_onto_base` and of the Marketing Agent's `merge_overlay`, on raw data: a section key replaces
    the base value; exclusion lists are the base's plus the overlay's new items."""
    effective = copy.deepcopy(base)
    for section in SECTIONS:
        values = overlay.get(section) or {}
        if values:
            effective.setdefault(section, {})
        for key, value in values.items():
            effective[section][key] = list(value) if isinstance(value, list) else value
    for key in EXCLUDE_KEYS:
        merged = list(effective.get(key) or [])
        seen = {_norm(x) for x in merged}
        for item in overlay.get(key) or []:
            if _norm(item) not in seen:
                seen.add(_norm(item))
                merged.append(item)
        effective[key] = merged
    # Replaces, and is present only when the campaign sets it (the Marketing Agent's merge_overlay does the same).
    if overlay.get("include_countries"):
        effective["include_countries"] = list(overlay["include_countries"])
    return effective


@lru_cache(maxsize=32)
def complete_file(overlay_yaml: str, campaign_id: str, version: int) -> CompleteFile:
    """Raises ContractViolation (a ValueError) if the result is not a valid complete file: it is then not offered."""
    overlay = parse_yaml(overlay_yaml)
    effective = merge_raw(overlay, base_raw())
    body = yaml.safe_dump(effective, sort_keys=False, allow_unicode=True, width=100)
    header = (
        "# Complete leadgen.yaml generated by the Campaign Agent. Do not edit by hand.\n"
        f"# campaign: {campaign_id}  version: {version}\n"
        f"# built on the base file with fingerprint {base_fingerprint()[:16]}\n"
    )
    text = f"{header}config_version: '{CONFIG_VERSION}'\n{body}"
    load_full(text)  # the full contract, on exactly the text that is sent
    return CompleteFile(text, hashlib.sha256(text.encode("utf-8")).hexdigest(), base_fingerprint())
